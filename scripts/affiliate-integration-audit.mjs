import {chromium} from "playwright";
import fs from "node:fs/promises";
import assert from "node:assert/strict";
const base=process.env.AUDIT_BASE_URL||"http://127.0.0.1:3000";
const path=async p=>fs.readFile(p,"utf8");
const checkout=await path("components/QuickCheckout.tsx");
const proxy=await path("app/api/checkout/route.ts");
const referral=await path("app/ref/[code]/route.ts");
const dashboard=await path("app/afiliados/page.tsx");
const sessions=await path("app/afiliados/actions.ts");
assert(checkout.includes('fetch("/api/checkout"'),"Checkout must use first-party referral aware proxy");
assert(proxy.includes("req.cookies.get(ATTRIBUTION_COOKIE)"),"Proxy must read secure attribution cookie");
assert(proxy.includes('affiliateToken:token'),"Proxy must forward signed referral token to Supabase");
assert(!checkout.includes('"affiliateToken":'),"Buyer cannot provide affiliate ownership from browser");
assert(referral.includes('action:"track"')&&referral.includes("httpOnly:true"),"Affiliate visits must be tracked with secure cookie");
assert(sessions.includes('action:"login"')&&sessions.includes("httpOnly:true"),"Affiliate login must use protected sessions");
assert(dashboard.includes("Clics")&&dashboard.includes("Ventas aprobadas"),"Panel must show visits and actual paid sales");
await fs.mkdir("visual-affiliate-funnel",{recursive:true});
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const report=[];
for(const view of [{name:"mobile320",width:320,height:700},{name:"mobile390",width:390,height:844},{name:"desktop",width:1440,height:900}]){
 const page=await browser.newPage({viewport:{width:view.width,height:view.height},isMobile:view.width<600,hasTouch:view.width<600});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto(base+"/afiliados",{waitUntil:"domcontentloaded"});
 await page.getByRole("button",{name:/Entrar al panel/}).waitFor();
 assert.equal(await page.locator('input[type="password"]').count(),1,"Login requires password");
 assert.equal(await page.locator('input[type="email"]').count(),1,"Login requires email");
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false,"Affiliate login overflows "+view.name);
 await page.screenshot({path:"visual-affiliate-funnel/"+view.name+"-login.png",fullPage:true});
 assert.deepEqual(errors,[],"Browser runtime errors "+view.name);
 report.push({view:view.name,login:true,fields:2,noOverflow:true});
 await page.close();
}
const page=await browser.newPage();
const invalid=await page.goto(base+"/ref/%21%21invalid",{waitUntil:"domcontentloaded"});
assert(invalid,"Unknown ref response missing");
assert.equal(new URL(page.url()).pathname,"/","Invalid referral should redirect safely to home");
assert.equal((await page.context().cookies()).some(c=>c.name==="thi_ref"),false,"Invalid referral must not set cookie");
const noBody=await page.request.post(base+"/api/checkout",{headers:{"content-type":"application/json"},data:"{"});
assert.equal(noBody.status(),400,"Bad checkout JSON must fail");
const noOrigin=await page.request.post(base+"/api/checkout",{headers:{"origin":"https://other.example","content-type":"application/json"},data:{experienceSlug:"pareja",email:"x@example.org",whatsapp:"5492215550000",consent:true,clientRequestId:"00000000-0000-4000-8000-000000000001"}});
assert.equal(noOrigin.status(),403,"Cross site checkout request must fail");
await page.close();await browser.close();
await fs.writeFile("visual-affiliate-funnel/report.json",JSON.stringify(report,null,2));
console.log("AFFILIATE FUNNEL AUDIT PASS",report);
