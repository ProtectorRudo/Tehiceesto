import test from 'node:test';
import assert from 'node:assert/strict';
import {initialState,processInbound} from '../src/flow.mjs';
import {goalChoices,nextWeekMonday} from '../src/huella-weekly-goals.mjs';
import {generatePremiumWeek} from '../src/huella-ai.mjs';

const today='2026-11-19',now='2026-11-19T19:00:00Z';
const run=(input,state)=>processInbound(input,{state,today,now});
const sequence=(inputs,seed=initialState())=>{
 let state=seed,all=[];
 for(const input of inputs){
  const result=run(input,state);
  state=result.state;all.push(...result.messages);
 }
 return {state,messages:all};
};
test('EMPEZAR after verified registration consent never asks consent twice',()=>{
 const s=initialState(),accepted='2026-11-01T13:40:00Z';s.consentAt=accepted;
 let r=run('EMPEZAR',s);
 assert.equal(r.state.status,'onboarding');
 assert.equal(r.state.flow,'adult_name');
 assert.equal(r.state.consentAt,accepted);
 assert.ok(!r.messages[0].body.includes('¿Aceptás'));
 assert.match(r.messages[0].body,/¿Cómo te gustaría/);
 r=run('EMPEZAR',r.state);
 assert.equal(r.state.flow,'adult_name');
 assert.equal(r.state.consentAt,accepted);
 r=run('Mauro',r.state);
 assert.equal(r.state.flow,'adult_role');
 assert.deepEqual(r.messages[0].options,['1','2','3','4','5']);
 assert.match(r.messages[0].body,/Mamá/);
 assert.match(r.messages[0].body,/Papá/);
 r=run('2',r.state);
 assert.equal(r.state.adultRole,'Papá');
 assert.equal(r.state.flow,'children_count');
 assert.deepEqual(r.messages[0].options,['1','2','3','4','5','6']);
});
test('unverified new number must still explicitly authorize data and WhatsApp messages',()=>{
 let r=run('EMPEZAR',initialState());
 assert.equal(r.state.status,'pending');
 assert.equal(r.state.consentAt,null);
 assert.equal(r.state.flow,'consent');
 assert.match(r.messages[0].body,/¿Aceptás recibir/);
 r=run('ACEPTO',r.state);
 assert.equal(r.state.status,'onboarding');
 assert.equal(r.state.flow,'adult_name');
 assert.equal(r.state.consentAt,now);
});
test('two-child onboarding accepts age-specific suggestions and a custom goal, no extra monthly or time-availability questions',()=>{
 const seed=initialState(),accepted='2026-11-01T13:40:00Z';seed.consentAt=accepted;
 let state=seed,output=[],r;
 const next=input=>{r=run(input,state);state=r.state;output.push(...r.messages);return r;};
 next('EMPEZAR');
 next('Mauro');
 next('Papá');
 next('2');
 next('Kaia');
 next('0');
 assert.equal(state.flow,'child_age_months');
 next('OMITIR');
 assert.equal(state.flow,'child_age_months','baby age must not remain unknown before mission generation');
 next('6');
 assert.equal(state.flow,'child_interests');
 assert.match(r.messages[0].body,/canciones/);
 next('música, libros');
 assert.equal(state.flow,'child_goal');
 const suggested=goalChoices(state.children[0],nextWeekMonday(today),0);
 assert.match(r.messages[0].body,/1\./);
 assert.match(r.messages[0].body,/Escribir mi propio objetivo/);
 next('1');
 assert.equal(state.children[0].goal,suggested[0]);
 next('Allegra');
 next('9');
 next('dibujar, fútbol');
 assert.equal(state.flow,'child_goal');
 next('4');
 assert.equal(state.flow,'child_goal_custom');
 next('Conversar con confianza y escucharnos mejor');
 assert.equal(state.flow,'delivery_time');
 assert.match(r.messages[0].body,/1\. 08:00/);
 next('1');
 assert.equal(state.status,'active');
 assert.equal(state.flow,'idle');
 assert.equal(state.adultRole,'Papá');
 assert.equal(state.adultName,'Mauro');
 assert.equal(state.children.length,2);
 assert.equal(state.children[0].ageMonths,6);
 assert.deepEqual(state.children[0].interests,['música','libros']);
 assert.equal(state.children[1].goal,'Conversar con confianza y escucharnos mejor');
 assert.equal(state.deliveryTime,'08:00');
 assert.equal(state.monthlyGoal,'');
 assert.equal(state.consentAt,accepted);
 assert.equal(state.huellaPilotStartDay,null);
 assert.ok(!output.some(x=>/¿Cuánto tiempo (real|tenés)/i.test(x.body)));
 assert.ok(!output.some(x=>/objetivo familiar de crianza para este mes/i.test(x.body)));
 let profile=run('DATOS',state);
 assert.match(profile.messages[0].body,/Vínculo: Papá/);
 assert.match(profile.messages[0].body,/Kaia \(6 meses/);
 assert.match(profile.messages[0].body,/Allegra \(9\)/);
});
test('profile registration retains the pending question when interrupted and rejects invalid roles',()=>{
 const s=initialState();s.consentAt=now;
 let r=sequence(['EMPEZAR','Ana','un vínculo desconocido'],s);
 assert.equal(r.state.flow,'adult_role');
 assert.equal(r.state.adultRole,null);
 assert.match(r.messages.at(-1).body,/Mamá/);
 r=sequence(['MENÚ','Cuidador/a'],r.state);
 assert.equal(r.state.flow,'children_count');
 assert.equal(r.state.adultRole,'Cuidador/a');
 r=sequence(['EMPEZAR','3','Nombre'],r.state);
 assert.equal(r.state.flow,'child_age');
 assert.equal(r.state.expectedChildren,3);
 assert.equal(r.state.children[0].name,'Nombre');
});
test('existing adults are never sent through onboarding when typing EMPEZAR',()=>{
 const s=initialState();s.status='active';s.consentAt=now;s.flow='idle';s.adultName='Ana';
 const r=run('EMPEZAR',s);
 assert.equal(r.state.status,'active');
 assert.equal(r.state.flow,'idle');
 assert.equal(r.state.consentAt,now);
 assert.match(r.messages[0].body,/registro ya está completo/);
});
